def _save_failed_answer(filename: str, content: str) -> None:
    """Сырой ответ модели, который не удалось разобрать как JSON, — для разбора (data/facts_cache/_failed)."""
    if not content:
        return
    import os
    folder = os.path.join(os.environ.get("FACTS_CACHE_DIR", os.path.join("data", "facts_cache")), "_failed")
    try:
        os.makedirs(folder, exist_ok=True)
        safe = re.sub(r'[^\w.\-]+', '_', filename)[:80]
        with open(os.path.join(folder, f"{safe}.txt"), "w", encoding="utf-8") as f:
            f.write(content)
        print(f"    ℹ Ответ модели сохранён для разбора: {os.path.join(folder, safe)}.txt")
    except OSError:
        pass


def _fix_inner_quotes(raw: str) -> str:
    """
    «"название": "ТОО "Zhana Business"", "что": …» — кавычка внутри строки считается закрывающей, только если за ней
    (через пробелы) идёт , : } ] или конец; иначе это кавычка в тексте, и она заменяется на «».
    """
    out, in_str, inner_open, i, n = [], False, False, 0, len(raw)
    while i < n:
        ch = raw[i]
        if not in_str:
            in_str = ch == '"'
            out.append(ch)
        elif ch == '\\' and i + 1 < n:
            out.append(raw[i:i + 2])
            i += 1
        elif ch == '"':
            j = i + 1
            while j < n and raw[j] in ' \t\r\n':
                j += 1
            if j >= n or raw[j] in ',:}]':
                out.append('"')
                in_str, inner_open = False, False
            else:
                out.append('»' if inner_open else '«')
                inner_open = not inner_open
        else:
            out.append(ch)
        i += 1
    return ''.join(out)


def _repair_json(raw: str) -> str:
    """Типовые огрехи JSON от модели: кавычки внутри значений, пропущенные и лишние запятые."""
    s = re.sub(r'\\(?!["\\/bfnrtu])', r'\\\\', raw)                # «C:\x», «№12\3» — недопустимый escape
    s = re.sub(r',\s*([}\]])', r'\1', s)                           # [1, 2,] / {"a": 1,}
    s = re.sub(r'(["\d\]}]|true|false|null)\s*\n\s*(["{\[])', r'\1,\n\2', s)  # элементы на разных строках без запятой
    s = re.sub(r'}\s*{', '},{', s)
    s = re.sub(r'"\s+"(?=[^:]*":)', '", "', s)                    # "a" "b": …
    return _fix_inner_quotes(s)


