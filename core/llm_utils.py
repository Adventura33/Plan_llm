class LLMClient:
    def __init__(self, api_url: str = DEFAULT_API_URL, model: str = DEFAULT_MODEL):
        self.api_url = api_url.rstrip('/')
        self.model = model
        if not self.api_url.endswith('/chat/completions'):
            self.endpoint = f"{self.api_url}/chat/completions"
        else:
            self.endpoint = self.api_url

    def _call_api(self, messages: List[Dict], temperature: float = 0.1, max_tokens: int = 8192) -> str:
        payload = {
            "model": self.model,
            "messages": messages,
            "temperature": temperature,
            "max_tokens": max_tokens,
        }

        # Диагностика: логируем суммарный размер промпта
        total_chars = sum(len(m.get("content", "")) for m in messages)
        if total_chars > 15000:
            print(f"  ⚠ Большой промпт: {total_chars:,} символов (~{total_chars//4:,} токенов)")

        headers = {"Content-Type": "application/json"}
        try:
            response = requests.post(self.endpoint, json=payload, headers=headers, timeout=360)
            response.raise_for_status()
        except requests.exceptions.HTTPError as e:
            if e.response is not None and e.response.status_code == 400:
                raise RuntimeError(
                    f"400 Bad Request — скорее всего промпт слишком большой "
                    f"({total_chars:,} симв.). Уменьшите retrieved_context."
                ) from e
            raise

        result = response.json()
        content = result['choices'][0]['message']['content']
        # Удаляем блоки рассуждений (например, <think>...</think>), которые выдают reasoning-модели
        content = re.sub(r'<think>.*?</think>', '', content, flags=re.DOTALL).strip()
        return content


