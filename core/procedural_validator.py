# core/procedural_validator.py
"""
Модуль процессуальной валидации и выравнивания логики расследования (Procedural Validator).
Проверяет соответствие действий нормам УПК РК:
1. Гарантирует обязательные первые 3 пункта плана в строго установленной формулировке.
2. Требует санкционирования постановления о производстве выемки/обыска ДО проведения самой выемки/обыска.
3. Обеспечивает процессуальную цепочку: Выемка/обыск -> Протокол осмотра изъятого -> Постановление о признании вещественными доказательствами.
4. Требует обязательного указания ПРОИСХОЖДЕНИЯ объекта анализа в аналитических пунктах.
5. Исправляет нереалистичные цели вывода из проверок СИО ПСО (СИО ПСО не устанавливает факт легализации/использования похищенного).
6. Исключает дублирование пунктов по анализу БВУ (снятие наличности, переводы третьим лицам) и проверкам имущества (СИО ПСО vs НАО).
7. Запрещает обыски/выемки у адвокатов (защитников).
8. Корректирует статус допроса экспертов (эксперт не допрашивается как свидетель).
9. Сортирует действия по 7 последовательным блокам УПК РК.
"""

import re
from typing import List, Dict, Optional

# 7 процессуальных блоков УПК РК
PROCEDURAL_BLOCKS = [
    "БЛОК 1: Фиксация доказательств и осмотры",
    "БЛОК 2: Запросы в уполномоченные органы",
    "БЛОК 3: Финансовый след и анализ БВУ",
    "БЛОК 4: Проверка активов фигурантов",
    "БЛОК 5: Допросы свидетелей и специалистов",
    "БЛОК 6: Судебные экспертизы",
    "БЛОК 7: Допросы подозреваемых",
    "БЛОК 8: Арест имущества и обеспечение возмещения ущерба",
    "БЛОК 9: Проверка показаний (очные ставки, проверка показаний на месте)",
]

_ARREST_RE = r'наложени\w*\s+арест|арест\w*\s+(?:на\s+)?(?:имуществ|денежн|сч[её]т|дол)|о\s+наложении\s+арест'
_VERIFY_RE = r'очн\w*\s+ставк|проверк\w*\s+показаний'


def fix_expert_witness_status(action_text: str) -> str:
    """
    Если в тексте действия упоминается эксперт или специалист,
    исправляет формулировку "допросить в качестве свидетеля" на "допросить в качестве эксперта / специалиста".
    """
    if not action_text:
        return action_text

    lower_text = action_text.lower()
    # Речь о лице со статусом эксперта/специалиста, а не о назначении экспертизы
    role_m = re.search(r'(?:в\s+качестве|привлеченн\w*|привлечённ\w*)\s+(?:\w+\s+)?(эксперт|специалист)\w*', lower_text) \
        or re.search(r'допрос\w*\s+(?:\w+\s+){0,2}(эксперт|специалист)(?!из)\w*', lower_text)
    if role_m and 'свидетел' in lower_text:
        role = role_m.group(1)
        # «Допросить свидетеля, привлеченного в качестве эксперта по ...» -> «Допросить эксперта по ...»
        action_text = re.sub(r'(допрос\w*\s+)свидетел\w*,?\s+привлеч[её]нн\w*\s+в\s+качестве\s+(?:эксперт|специалист)\w*',
                             rf'\g<1>{role}а', action_text, count=1, flags=re.IGNORECASE)
        action_text = re.sub(r'(допрос\w*\s+)(?:в\s+качестве\s+)?свидетел\w*', rf'\g<1>{role}а',
                             action_text, count=1, flags=re.IGNORECASE)
        action_text = re.sub(r'в\s+качестве\s+свидетеля', f'в качестве {role}а', action_text, flags=re.IGNORECASE)
        print(f"  ⚖ [ProceduralValidator] Исправлен статус с 'свидетеля' на '{role}а'")

    return action_text


def is_forbidden_attorney_action(action_text: str) -> bool:
    """
    Проверяет, содержит ли действие запрещенные процессуальные мероприятия в отношении адвокатов.
    """
    if not action_text:
        return False

    lower_text = action_text.lower()
    # Участие защитника в допросе/очной ставке подозреваемого допустимо и обязательно —
    # такие упоминания не считаются действием В ОТНОШЕНИИ адвоката
    target_text = re.sub(
        r'(?:с\s+участием|при\s+участии|в\s+присутствии)\s+(?:его\s+|её\s+|ее\s+)?(?:адвокат|защитник)\w*',
        '', lower_text)
    if not re.search(r'адвокат|защитник', target_text):
        return False

    prohibited = r'обыск|выемк|допрос|очн\w*\s+ставк|осмотр\s+личных\s+вещей|изъят|истребова'
    if re.search(prohibited, target_text):
        print(f"  🚫 [ProceduralValidator] Заблокировано неправомерное действие с адвокатом: '{action_text[:70]}...'")
        return True

    return False


def is_forbidden_search_of_witness_or_victim(action_text: str) -> bool:
    """
    Обыск у свидетеля или потерпевшего не соответствует их процессуальному статусу:
    обыск проводится по месту жительства/работы подозреваемого. У свидетелей и потерпевших
    документы и предметы получают выемкой или добровольной выдачей.
    """
    if not action_text:
        return False
    lower_text = action_text.lower()
    if re.search(r'обыск\w*\s+(?:[\w«»"\-.]+\s+){0,4}?(?:у|в\s+жилище|по\s+месту\s+(?:жительства|работы|регистрации))\s+'
                 r'(?:\w+\s+){0,2}?(?:свидетел|потерпевш)\w*', lower_text) \
            and not re.search(r'подозреваем|обвиняем', lower_text):
        print(f"  🚫 [ProceduralValidator] Заблокирован обыск у свидетеля/потерпевшего: '{action_text[:70]}...'")
        return True
    return False


def is_forbidden_coercive_action_against_protected_person(action_text: str) -> bool:
    """
    Проверяет, содержит ли действие запрещённые принудительные мероприятия
    в отношении лиц, не являющихся фигурантами: прокуроров, привлечённых
    специалистов (ДВГА, аудиторов, оценщиков, ревизоров), экспертов.

    Принудительные меры (обыск, выемка, арест имущества, очная ставка,
    изъятие электронных носителей) допустимы ТОЛЬКО в отношении
    подозреваемых/обвиняемых.

    Допустимые действия в отношении специалистов/экспертов:
    - Допрос (по порядку проведения исследования, методике, выводам)
    - Истребование дополнительных материалов исследования
    """
    if not action_text:
        return False

    lower_text = action_text.lower()

    # Вид действия — по глаголу в начале пункта: допрос, истребование, ознакомление, назначение экспертизы
    # не принудительны ни для кого («Допросить подозреваемую … с предъявлением изъятых документов и заключения
    # аудитора» — допрос подозреваемой, а не изъятие у аудитора)
    if re.match(r'\s*(?:дополнительно\s+|повторно\s+)?допросить|\s*(?:провести|произвести)\s+(?:\w+\s+){0,2}?допрос|'
                r'\s*(?:истребовать|ознакомить|назначить\s+(?:\w+\s+){0,3}?экспертиз)|'
                # проверка показаний на месте и предъявление документов — не принудительные меры
                r'\s*(?:провести|произвести)\s+проверк\w*\s+показаний|\s*проверить\s+показания|\s*предъяв', lower_text):
        return False
    # Действие в отношении подозреваемого («Произвести выемку у подозреваемой … документов, указанных в заключении
    # аудитора») — не против аудитора. Очная ставка — с двумя участниками, её проверяем дальше
    if not re.search(r'очн\w*\s+ставк', lower_text) and re.match(
            r'\s*\S+(?:\s+\S+){0,3}?\s+(?:у\s+|в\s+отношении\s+|по\s+месту\s+жительства\s+)?(?:подозреваем|обвиняем)\w*',
            lower_text):
        return False

    # Маркеры защищённых ролей (не фигуранты)
    protected_role_keywords = [
        'прокурор', 'заместител прокурор', 'зам. прокурор', 'зам.прокурор',
        'помощник прокурор',
        'привлечённ специалист', 'привлеченн специалист',
        'специалист двга', 'специалиста двга',
        'аудитор', 'оценщик', 'ревизор',
        'эксперт',
    ]

    # Принудительные действия, запрещённые в отношении защищённых лиц
    coercive_action_keywords = [
        'обыск', 'выемк', 'изъят',
        'арест имущества', 'ограничени на имущество', 'ограничение на распоряжение',
        'наложени ограничен', 'наложении ограничен',
        'временн ограничени', 'временных ограничен',
        'арест на имущество',
        'очн ставк', 'очная ставка', 'очной ставк', 'очную ставку',
        'электронных носител', 'сотовых телефон', 'мобильных телефон',
        'планшет', 'флешкарт', 'жёстк дис', 'жестк дис',
    ]

    # Проверяем: есть ли в тексте одновременно защищённая роль И принудительное действие
    has_protected_role = False
    matched_role = ""
    # «экспертизу», «экспертизы» — это вид действия, а не лицо-эксперт; «согласно заключению эксперта» —
    # ссылка на доказательство («арест в пределах ущерба по заключению эксперта»), а не действие против эксперта
    lower_roles = re.sub(r'экспертиз\w*', ' ', lower_text)
    lower_roles = re.sub(r'заключени\w*\s+(?:\w+\s+){0,2}?(?:эксперт|специалист|аудитор|ревизор)\w*', ' ', lower_roles)
    # Участник действия («выемка … с участием специалиста») и источник сведений («ущерб, установленный аудитором»)
    # — не лицо, в отношении которого действие проводится
    lower_roles = re.sub(r'(?:с\s+участием|с\s+привлечением|при\s+участии)\s+(?:\w+\s+){0,2}?'
                         r'(?:эксперт|специалист|аудитор|ревизор|оценщик)\w*', ' ', lower_roles)
    lower_roles = re.sub(r'(?:установлен|выявлен|рассчитан|определ[её]н|подтвержд[её]н|указан)\w*\s+(?:\w+\s+){0,2}?'
                         r'(?:эксперт|специалист|аудитор|ревизор|оценщик)\w*', ' ', lower_roles)
    # Прокурор и судья как санкционирующие органы («с согласия прокурора», «ходатайствовать перед следственным
    # судьёй», «уведомить прокурора») — порядок действия, а не лицо, в отношении которого оно проводится
    lower_roles = re.sub(
        r'(?:согласи\w*|по\s+согласовани\w*\s+с|с\s+санкци\w*|санкционир\w*|уведомлени\w*|уведом\w*|'
        r'ходатайств\w*(?:\s+\w+){0,4}?\s+перед|перед|согласова\w*\s+с|надзирающ\w*)\s+'
        r'(?:\w+\s+){0,2}?(?:прокурор\w*|судь\w*|суд\w*)', ' ', lower_roles)
    for role_kw in protected_role_keywords:
        # Разбиваем ключевое слово на части для нечёткого поиска (учёт падежей)
        role_parts = role_kw.split()
        if all(part in lower_roles for part in role_parts):
            has_protected_role = True
            matched_role = role_kw
            break

    if not has_protected_role:
        return False

    # Проверяем: есть ли принудительное действие
    has_coercive = False
    matched_action = ""
    for action_kw in coercive_action_keywords:
        action_parts = action_kw.split()
        if all(part in lower_text for part in action_parts):
            has_coercive = True
            matched_action = action_kw
            break

    if has_coercive:
        # Исключение: допрос специалиста/эксперта — это ДОПУСТИМОЕ действие,
        # даже если в тексте есть слово «эксперт» или «специалист».
        # Блокируем только если действие НЕ является допросом.
        is_interrogation = any(k in lower_text for k in ['допрос', 'допросить', 'опрос', 'истребова'])
        is_only_interrogation = is_interrogation and not any(
            k in lower_text for k in ['обыск', 'выемк', 'арест', 'ограничен', 'изъят', 'очн']
        )

        if is_only_interrogation:
            return False  # Допрос специалиста/эксперта — разрешено

        print(f"  🚫 [ProceduralValidator] Заблокировано принудительное действие "
              f"('{matched_action}') в отношении защищённого лица ('{matched_role}'): "
              f"'{action_text[:80]}...'")
        return True

    return False

def _extract_seizure_target_and_place(case_data: Optional[Dict] = None) -> tuple:
    """
    Извлекает объект изъятия, период и наименование организации/место из case_data для формулирования
    полного конкретного действия по выемке/обыску и его санкционированию.
    """
    # Объект изъятия не привязываем к бухгалтерии: по ст.301-1, 214 и др. это товар, договоры займа,
    # залоговое имущество и т.п. Конкретику указывает LLM, здесь — только нейтральная формулировка.
    doc_types = "предметов и документов, имеющих значение для уголовного дела"
    period = "за проверяемый период"
    place = "офиса организации"

    if case_data:
        # Извлекаем организацию/место
        orgs = case_data.get('компании_фигурантов', case_data.get('компании', '')) or case_data.get('реальное_название_тоо', '')
        place_info = case_data.get('место_правонарушения', case_data.get('адреса_фигурантов', ''))
        fabula = case_data.get('фабула') or case_data.get('суть_правонарушения', '') or ''

        extracted_org = None
        if isinstance(orgs, list) and orgs:
            extracted_org = str(orgs[0])
        elif isinstance(orgs, str) and orgs and orgs != 'Н/Д':
            extracted_org = orgs

        if not extracted_org and fabula:
            # ИП с ФИО и инициалами: «ИП Сапаров Д.К.»
            ip_match = re.search(r'\bИП\s+[А-ЯЁ][а-яё]+(?:\s+[А-ЯЁ]\.\s?[А-ЯЁ]\.)?', fabula)
            if ip_match:
                extracted_org = ip_match.group(0).strip()
        if not extracted_org and fabula:
            # Ищем название организации в фабуле (КГКП ..., ТОО ..., АО ..., ГККП ...)
            match = re.search(r'((?:КОММУНАЛЬНОГО ГОСУДАРСТВЕННОГО КАЗЕННОГО ПРЕДПРИЯТИЯ|КГКП|ГККП|ГКП|ТОО|АО|ИП|ГКП на ПХВ)\s+[«""][^»""]+[»""]|(?:КГКП|ГККП|ГКП|ТОО|АО|ИП|ГКП на ПХВ)\s+[А-Яа-я0-9\s№-]+)', fabula, flags=re.IGNORECASE)
            if match:
                extracted_org = match.group(1).strip()

        if extracted_org:
            if not extracted_org.lower().startswith('офис'):
                place = f"офиса {extracted_org}"
            else:
                place = extracted_org
        elif place_info and place_info != 'Н/Д':
            place = f"помещения {place_info}"

        # Извлекаем период
        d_start = case_data.get('дата_начала_периода', '')
        d_end = case_data.get('дата_окончания_периода', case_data.get('дата_регистрации_ердр', ''))
        if d_start and d_end and d_start != 'Н/Д' and d_end != 'Н/Д':
            period = f"за период с {d_start} по {d_end}"
        elif fabula:
            # «в период с 01.01.2023 года по 28.02.2025 года»; иначе — самая ранняя и самая поздняя дата
            # (фабула часто начинается с даты регистрации: «30.04.2025 года … в период с 01.01.2023 …»)
            m = re.search(r'\bс\s+(\d{2}\.\d{2}\.\d{4})\D{0,12}?по\s+(\d{2}\.\d{2}\.\d{4})', fabula)
            dates = re.findall(r'\d{2}\.\d{2}\.\d{4}', fabula)
            chrono = sorted(set(dates), key=lambda d: (d[6:], d[3:5], d[:2]))
            if m:
                period = f"за период с {m.group(1)} по {m.group(2)}"
            elif len(chrono) >= 2:
                period = f"за период с {chrono[0]} по {chrono[-1]}"
            elif len(chrono) == 1:
                period = f"за период с {chrono[0]}"

    return doc_types, period, place


def _extract_main_figurant_name(case_data: Optional[Dict] = None, text: str = "") -> str:
    """
    Извлекает ФИО главного фигуранта из текста действия или case_data.
    """
    if text:
        init_match = re.search(r'([А-Яа-яА-ӘөңғүұқөһІі]+\s+[А-Я]\.\s*[А-Я]\.)', text)
        if init_match:
            return init_match.group(1).strip()

    if case_data:
        figs = case_data.get('фигуранты', '')
        if isinstance(figs, list) and figs:
            f0 = figs[0]
            return f0.get('фио', '') if isinstance(f0, dict) else str(f0)
        elif isinstance(figs, str) and figs and figs != 'Н/Д':
            return figs.split(',')[0].strip()

    return "проверяемых лиц"


def _is_post_seizure_step(text_lower: str) -> bool:
    """Осмотр изъятого / признание вещественными доказательствами / экспертиза изъятого."""
    return bool(re.search(r'осмотр|вещественн|признании\s+в\s+качестве|экспертиз', text_lower))


def _is_seizure_execution(text_lower: str) -> bool:
    """Пункт — это само производство выемки/обыска (а не санкция, осмотр или упоминание)."""
    if _is_post_seizure_step(text_lower):
        return False
    if any(s in text_lower for s in ['санкционир', 'ходатайств', 'постановлен']):
        return False
    return bool(re.match(r'\s*(?:произвести|провести|осуществить)?\s*(?:выемк|обыск)', text_lower))


def fix_seizure_sanction_wording(action_text: str, case_data: Optional[Dict] = None) -> str:
    """
    Правило: Пункт относительно выемки/обыска и санкционирования ОБЯЗАТЕЛЬНО должен содержать:
    1. Конкретный объект изъятия (первичных бухгалтерских документов, приказов о назначении на должность, табелей учета рабочего времени и т.д.)
    2. Период (за период с DD.MM.YYYY по DD.MM.YYYY)
    3. Место/организацию (из офиса КГКП...)
    Формулировка: «Вынести постановление о производстве выемки <объект> за период <период> из <место> и в установленном порядке ходатайствовать перед следственным судьей о его санкционировании».
    """
    if not action_text:
        return action_text

    text_lower = action_text.lower()

    # Осмотр изъятого и признание вещдоками лишь упоминают выемку/обыск — это не санкционирование
    if _is_post_seizure_step(text_lower):
        return action_text

    # 1. Если действие про санкционирование или ходатайство по выемке/обыску
    if ('выемк' in text_lower or 'обыск' in text_lower) and any(k in text_lower for k in ['постановлен', 'санкционир', 'ходатайств']):
        # Обыск остаётся обыском: подмена на «выемку» меняет процессуальную природу действия
        is_search = 'обыск' in text_lower and 'выемк' not in text_lower
        act_noun = "обыска" if is_search else "выемки"
        # Содержательный текст от LLM (объект, место) сохраняется; заменяется только пустая формулировка
        stripped = re.sub(r'(?i)вынести|санкционир\w*|ходатайств\w*|постановлени\w*|о производстве|'
                          r'выемк\w*|обыск\w*|следственн\w+ суд\w*|перед|в установленном порядке|о его|и\b|[.,;()]', ' ', action_text)
        has_substance = len(re.findall(r'[А-Яа-яЁё]{3,}', stripped)) >= 3

        if not has_substance:
            doc_types, period, place = _extract_seizure_target_and_place(case_data)
            action_text = (f"Вынести постановление о производстве {act_noun} {doc_types} {period} из {place} "
                           f"и в установленном порядке ходатайствовать перед следственным судьей о его санкционировании")
            print(f"  ⚖ [ProceduralValidator] Дополнена формулировка санкционирования {act_noun} (объект, период, место)")
        elif 'санкционир' not in text_lower and 'ходатайств' not in text_lower:
            action_text = action_text.rstrip(' .,;') + " и в установленном порядке ходатайствовать перед следственным судьей о его санкционировании"

    # 2. Выемка: нормализация формулировки отдельного исполнительного пункта
    elif 'выемк' in text_lower and not any(k in text_lower for k in ['постановлен', 'санкционир', 'ходатайств']):
        if re.search(r'^\s*провести\s+выемку', action_text, flags=re.IGNORECASE):
            action_text = re.sub(
                r'^\s*провести\s+выемку',
                'Произвести выемку',
                action_text,
                flags=re.IGNORECASE
            )
        elif re.search(r'^\s*выемка\b', action_text, flags=re.IGNORECASE):
            action_text = re.sub(
                r'^\s*выемка\b',
                'Произвести выемку',
                action_text,
                flags=re.IGNORECASE
            )

    # 3. Обыск: нормализация формулировки отдельного исполнительного пункта
    elif 'обыск' in text_lower and not any(k in text_lower for k in ['постановлен', 'санкционир', 'ходатайств']):
        if re.search(r'^\s*провести\s+обыск', action_text, flags=re.IGNORECASE):
            action_text = re.sub(
                r'^\s*провести\s+обыск',
                'Произвести обыск',
                action_text,
                flags=re.IGNORECASE
            )

    return action_text


# Начало пункта «Санкционировано постановление …», «Санкционировать постановление …», «Санкционирование
# постановления …», «Санкционировать (и произвести) выемку / обыск …», «Санкционировать проведение обыска …»
_SANCTION_LEAD = re.compile(
    r'^\s*санкционир\w*\s+(?:и\s+произвести\s+)?(?:(?:следственн\w+\s+суд\w+|прокурор\w*)\s+)?'
    r'(?:(?:проведени\w*|производств\w*)\s+)?'
    r'(?:(?P<decree>постановлени\w*)\s+|(?P<act>(?:личн\w+\s+)?(?:выемк\w*|обыск\w*))\b\s*)',
    re.IGNORECASE)
# Хвост старого автошаблона: «… о его санкционировании (санкционировано постановление о производстве выемки …)»
_SANCTION_TAIL = re.compile(r'\s*\(\s*санкционировано[^)]*\)', re.IGNORECASE)
_JUDGE_PETITION = 'в установленном порядке ходатайствовать перед следственным судьей о его санкционировании'


def fix_sanction_tense(action_text: str) -> str:
    """
    Неисполненный пункт плана — задание исполнителю, а не отметка о факте (автор, 09.11.2026: «исправь везде»).
    «Санкционировано постановление о производстве выемки …» читается как уже полученная санкция, «Санкционировать
    постановление …» — как полномочие следователя, хотя санкцию даёт следственный судья по его ходатайству:
      • «Санкционировано (Санкционировать) постановление о производстве выемки (обыска) X», «Санкционировать выемку X»
        -> «Вынести постановление о производстве выемки (обыска) X и в установленном порядке ходатайствовать перед
        следственным судьей о его санкционировании»;
      • «… постановление о наложении ареста X» без ходатайства -> «Ходатайствовать перед следственным судьей о
        санкционировании постановления о наложении ареста X» (само постановление об аресте — свой пункт);
      • иное постановление («о получении банковских выписок …») -> «Вынести постановление … и в установленном порядке
        ходатайствовать о его санкционировании» (кто санкционирует — не дописывается);
      • ходатайство в тексте уже есть — меняется только начало: «Вынести постановление …».
    Хвост «(санкционировано постановление …)» старого автошаблона убирается. Исполненные пункты сюда не передаются:
    у них прошедшее время — отметка о факте.
    """
    if not action_text:
        return action_text
    text = _SANCTION_TAIL.sub('', action_text)
    m = _SANCTION_LEAD.match(text)
    if not m:
        return text
    rest = text[m.end():].strip()
    if m.group('act'):
        act = m.group('act').lower()
        noun = ('личного обыска' if act.startswith('личн') else 'обыска') if 'обыск' in act else 'выемки'
        rest = f"о производстве {noun} {rest}".strip()
    has_petition = bool(re.search(r'ходатайств', rest, re.IGNORECASE))
    if has_petition:
        return f"Вынести постановление {rest}"
    if re.match(r'(?:о\s+наложени\w*\s+арест|об?\s+арест)', rest, re.IGNORECASE):
        return f"Ходатайствовать перед следственным судьей о санкционировании постановления {rest}"
    # точка в конце — не точка инициала («… Иванова И.И.»)
    body = re.sub(r'(?<![А-ЯЁA-Z])\.+$', '', rest.rstrip(' ,;')).rstrip(' ,;')
    tail = _JUDGE_PETITION if re.match(r'о\s+производстве\s+(?:личного\s+)?(?:обыска|выемки)', body, re.IGNORECASE) \
        else 'в установленном порядке ходатайствовать о его санкционировании'
    return f"Вынести постановление {body} и {tail}"


# «Провести проверку показаний X и Y посредством очной ставки …» — это очная ставка (ст. 218 УПК РК);
# проверка показаний на месте — другое следственное действие (этап «Проверка показаний» методики)
_CONFRONTATION_AS_CHECK = re.compile(
    r'^\s*(?:провести\s+проверку\s+показаний|проверить\s+показания)\s+(?P<who>.+?)\s+'
    r'(?:посредством|путем|путём)\s+(?:проведения\s+)?очн\w+\s+ставк\w*(?P<rest>.*)$', re.IGNORECASE | re.S)
# Родительный падеж -> творительный после «между»: роли и мужские фамилии («Иванова И.И.» -> «Ивановым И.И.»);
# женские фамилии на -ой и казахские на -улы/-кызы в этих падежах совпадают
_ROLE_INSTR = [(r'\b(подозреваем|обвиняем)ого\b', r'\1ым'), (r'\bпотерпевшего\b', 'потерпевшим'),
               (r'\bсвидетеля\b', 'свидетелем'), (r'\bсвидетельницы\b', 'свидетельницей'),
               (r'\bпредставителя\b', 'представителем')]
_SURNAME_INSTR = [(r'(ов|ев|ёв|ин|ын)а$', r'\1ым'), (r'(ск|цк)ого$', r'\1им')]


def _to_instrumental(who: str) -> str:
    from core.case_participants import find_person_mentions, normalize_text
    for pat, rep in _ROLE_INSTR:
        who = re.sub(pat, rep, who, flags=re.IGNORECASE)
    for p in sorted(find_person_mentions(normalize_text(who)), key=lambda p: -p['start']):
        surname = who[p['start']:p['start'] + len(p['surname'])]
        for pat, rep in _SURNAME_INSTR:
            if re.search(pat, surname):
                who = who[:p['start']] + re.sub(pat, rep, surname) + who[p['start'] + len(p['surname']):]
                break
    return who


# «Проверить показания X и Y на предмет противоречий …» — сверка показаний двух лиц при противоречиях
# и есть очная ставка; «проверка показаний на месте» и проверка показаний одного лица не затрагиваются
_TWO_PERSON_CHECK = re.compile(
    r'^\s*(?:провести\s+проверку\s+показаний|проверить\s+показания)\s+(?P<who>.+?)'
    r'(?P<rest>\s+(?:на\s+предмет|по\s+вопрос\w*|в\s+части|относительно|для\s+устранения|при\s+наличии|об?)\s.*)$',
    re.IGNORECASE | re.S)


def fix_confrontation_wording(action_text: str) -> str:
    """
    «Провести проверку показаний X и Y посредством очной ставки …» и «Проверить показания X и Y на предмет
    противоречий …» -> «Провести очную ставку между X и Y …».
    """
    from core.case_participants import find_person_mentions, normalize_text
    m = _CONFRONTATION_AS_CHECK.match(action_text or '')
    if not m:
        two = _TWO_PERSON_CHECK.match(action_text or '')
        if not two or not re.search(r'противореч', action_text, re.IGNORECASE) \
                or re.search(r'на\s+месте', action_text, re.IGNORECASE) \
                or len(find_person_mentions(normalize_text(two.group('who')))) < 2:
            return action_text
        rest = re.sub(r'^\s+на\s+предмет\s+противоречий', ' для устранения противоречий', two.group('rest'),
                      flags=re.IGNORECASE)
        # «…, при наличии расхождений — провести очную ставку» — после правки это повтор
        rest = re.sub(r'[,;]?\s*(?:при\s+наличии\s+(?:расхождений|противоречий)\s*[—–-]?\s*)?провести\s+очн\w+\s+ставк\w*'
                      r'\s*[.;]?\s*$', '', rest, flags=re.IGNORECASE)
        fixed = f"Провести очную ставку между {_to_instrumental(two.group('who').strip())}{rest}"
        print(f"  ⚖ [ProceduralValidator] Сверка показаний двух лиц при противоречиях -> очная ставка: '{fixed[:80]}...'")
        return fixed
    who, rest = _to_instrumental(m.group('who').strip()), m.group('rest')
    # «показаний Иванова И.И. посредством очной ставки с Петровым П.П. …» — второй участник уже в творительном
    second = re.match(r'\s+с\s+(.+)$', rest, re.S)
    fixed = f"Провести очную ставку между {who} и {second.group(1)}" if second else f"Провести очную ставку между {who}{rest}"
    print(f"  ⚖ [ProceduralValidator] «Проверка показаний посредством очной ставки» -> очная ставка: '{fixed[:80]}...'")
    return fixed


def fix_origin_of_analyzed_object(action_text: str) -> str:
    """
    Правило: В пунктах анализа операций, выписок, снятия наличных средств, транзакций и финансовых документов
    ОБЯЗАТЕЛЬНО должно указываться происхождение объекта анализа (полученные из БВУ / через БД СИО ПСО).
    """
    if not action_text:
        return action_text

    text_lower = action_text.lower()
    # Только пункты, которые САМИ являются анализом (а не «допросить эксперта по анализу транзакций»)
    if re.match(r'\s*(?:проанализировать|провести\s+анализ|проведение\s+анализа|анализ)\b', text_lower):
        if any(k in text_lower for k in ['сняти', 'выпис', 'транзакц', 'перевод', 'движен', 'банковск']):
            origin_keywords = [
                'полученн', 'изъят', 'истребованн', 'из бву', 'через сио псо',
                'через бд', 'из материалов', 'согласно выпискам', 'предоставленн'
            ]
            if not any(ok in text_lower for ok in origin_keywords):
                if re.search(r'^\s*(проанализировать|анализ)\b', action_text, flags=re.IGNORECASE):
                    action_text = re.sub(
                        r'^\s*(проанализировать|анализ)\b',
                        r'Проанализировать по банковским выпискам, полученным через БД СИО ПСО / из БВУ,',
                        action_text,
                        flags=re.IGNORECASE
                    )
                else:
                    action_text = f"Проанализировать по банковским выпискам (полученным через БД СИО ПСО / из БВУ): {action_text}"
                print("  ⚖ [ProceduralValidator] Указано происхождение объекта анализа")

    return action_text


def fix_sio_pso_goal(action_dict: Dict) -> Dict:
    """
    Правило: Проверка по СИО ПСО устанавливает только факт наличия/отсутствия регистрации прав/юридических лиц.
    Вывод об 'использовании похищенных средств для создания бизнес-структур с целью легализации' сделать через СИО ПСО невозможно.
    """
